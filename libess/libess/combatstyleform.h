class CombatStyleForm : public Form
{
protected:
	char *editorID;
	CombatStyleBasic basic;
	CombatStyleBasic2 basic2;
	CombatStyleBasic3 basic3;
	CombatStyleBasic4 basic4;
	CombatStyleBasic5 basic5;
	CombatStyleBasic6 basic6;
	CombatStyleAdvanced advanced;
	bool advancedSeen;
	bool smallbasic;
	bool smallbasic2;
	bool smallbasic3;
	bool smallbasic4;
	bool smallbasic5;
public:
	CombatStyleForm(FormHeader h,ModFile *f) : Form(h,f), editorID(0), advancedSeen(false), smallbasic(false), smallbasic2(false), smallbasic3(false), smallbasic4(false), smallbasic5(false)
	{
	}
	virtual ~CombatStyleForm()
	{
		if (editorID)
		{
			delete[] editorID;
		}
	}
protected:
	virtual void Load(FileRead *f)
	{
		while (readSize < uncompsize)
		{
			SubrecordHeader h = ReadSubrecord(f);
			switch(h.type)
			{
			case 'EDID':
				editorID = f->readzstring(h.size);
				readSize += h.size;
				break;
			case 'CSTD':
				if (h.size == sizeof(CombatStyleBasic))
				{
					basic = f->read<CombatStyleBasic>();
					readSize += sizeof(CombatStyleBasic);
				}
				else if (h.size == sizeof(CombatStyleBasic2))
				{
					smallbasic = true;
					basic2 = f->read<CombatStyleBasic2>();
					readSize += sizeof(CombatStyleBasic2);
				}
				else if (h.size == sizeof(CombatStyleBasic3))
				{
					smallbasic2 = true;
					basic3 = f->read<CombatStyleBasic3>();
					readSize += sizeof(CombatStyleBasic3);
				}
				else if (h.size == sizeof(CombatStyleBasic4))
				{
					smallbasic3 = true;
					basic4 = f->read<CombatStyleBasic4>();
					readSize += sizeof(CombatStyleBasic4);
				}
				else if (h.size == sizeof(CombatStyleBasic5))
				{
					smallbasic4 = true;
					basic5 = f->read<CombatStyleBasic5>();
					readSize += sizeof(CombatStyleBasic5);
				}
				else
				{
					smallbasic5 = true;
					basic6 = f->read<CombatStyleBasic6>();
					readSize += sizeof(CombatStyleBasic6);
				}
				break;
			case 'CSAD':
				advancedSeen = true;
				advanced = f->read<CombatStyleAdvanced>();
				readSize += sizeof(CombatStyleAdvanced);
				break;
			default:
				printf("Unknown subrecord found");
				__debugbreak();
				break;
			}
		}
	}
	virtual void Save(FileWrite *f)
	{
		WriteZStringSubrecord('EDID',editorID,f);
		if (smallbasic)
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic2),f);
			f->write<CombatStyleBasic2>(basic2);
		}
		else if (smallbasic2)
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic3),f);
			f->write<CombatStyleBasic3>(basic3);
		}
		else if (smallbasic3)
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic4),f);
			f->write<CombatStyleBasic4>(basic4);
		}
		else if (smallbasic4)
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic5),f);
			f->write<CombatStyleBasic5>(basic5);
		}
		else if (smallbasic5)
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic6),f);
			f->write<CombatStyleBasic6>(basic6);
		}
		else
		{
			WriteSubrecord('CSTD',sizeof(CombatStyleBasic),f);
			f->write<CombatStyleBasic>(basic);
		}
		if (advancedSeen)
		{
			WriteSubrecord('CSAD',sizeof(CombatStyleAdvanced),f);
			f->write<CombatStyleAdvanced>(advanced);
		}
	}
	virtual int GetSaveSize()
	{
		int size = 0;
		size += ZStringSubrecordSize(editorID);
		if (smallbasic)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic2));
		}
		else if (smallbasic2)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic3));
		}
		else if (smallbasic3)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic4));
		}
		else if (smallbasic4)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic5));
		}
		else if (smallbasic5)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic6));
		}
		else
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleBasic));
		}
		if (advancedSeen)
		{
			size += ComputeSubrecordSize(sizeof(CombatStyleAdvanced));
		}
		return size;
	}
};
